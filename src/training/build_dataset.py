"""Phase 0/1: raw datasets -> unified per-host window parquet + dataset report.

    python -m src.training.build_dataset [--datasets cic2017 ctu13 unsw cic2018]

Writes data/processed/{name}.windows.parquet, {name}.edges.parquet and
reports/dataset_stats.md. Every capture is windowed independently through the
same fusion.windowize used at inference time.
"""
from __future__ import annotations

import argparse
import gc
import json
import time
from pathlib import Path

import pandas as pd

from src.features.flow_features import load_cic_csv, load_ctu13, load_unsw
from src.features.fusion import windowize
from src.mitre.mitre_lookup import label_to_stage, stage_names
from src.utils.config import PROCESSED, RAW, REPORTS, world_model_config

DATASETS = {
    "cic2017": lambda: [(p.stem.split(".")[0], lambda p=p: load_cic_csv(p))
                        for p in sorted((RAW / "CIC-IDS2017" / "TrafficLabelling").glob("*.csv"))],
    # Only the 20-02 day of CIC-IDS2018 keeps Src/Dst IP; the other 9 days are IP-stripped
    # and cannot form per-host timelines (documented in README).
    "cic2018": lambda: [("Tue-20-02-2018", lambda: load_cic_csv(
        RAW / "CIC-IDS2018" / "csv_features" / "Thuesday-20-02-2018_TrafficForML_CICFlowMeter.csv"))],
    "ctu13": lambda: [(f"scenario-{p.parent.name}", lambda p=p: load_ctu13(p))
                      for p in sorted((RAW / "CTU-13" / "_full" / "CTU-13-Dataset").glob("*/*.binetflow"),
                                      key=lambda q: int(q.parent.name))],
    "unsw": lambda: [("UNSW-NB15", lambda: pd.concat(
        [load_unsw(RAW / "UNSW-NB-15" / "unsw_nb15" / f"UNSW-NB15_{i}.csv") for i in range(1, 5)],
        ignore_index=True).sort_values("ts_end").reset_index(drop=True))],
}


def build(name: str, cfg: dict) -> dict:
    wcfg = cfg["windowing"]
    frames, edges, stats = [], [], []
    for cap, loader in DATASETS[name]():
        t = time.time()
        flows = loader()
        fm = windowize(flows, window_s=wcfg["window_s"], min_flows=wcfg["min_flows"],
                       max_hosts=wcfg["max_hosts"], source=name)
        df = fm.frame
        df.insert(0, "capture", cap)
        df.insert(0, "dataset", name)
        e = fm.edges.assign(dataset=name, capture=cap)
        frames.append(df)
        edges.append(e)
        s = {"capture": cap, "flows": len(flows),
             "attack_flows": int((flows["label"].map(
                 {l: label_to_stage(l) for l in flows["label"].unique()}) > 0).sum()),
             "hosts": df["host"].nunique(), "windows": len(df),
             "attack_windows": int((df["stage"] > 0).sum()),
             "labels": flows["label"].value_counts().head(12).to_dict(),
             "seconds": round(time.time() - t, 1)}
        print(json.dumps({k: v for k, v in s.items() if k != "labels"}))
        stats.append(s)
        del flows, fm
        gc.collect()
    out = pd.concat(frames, ignore_index=True)
    out.to_parquet(PROCESSED / f"{name}.windows.parquet", index=False)
    pd.concat(edges, ignore_index=True).to_parquet(PROCESSED / f"{name}.edges.parquet", index=False)
    stage_counts = out["stage"].value_counts().sort_index()
    return {"dataset": name, "captures": stats,
            "stage_windows": {stage_names()[int(k)]: int(v) for k, v in stage_counts.items()}}


def write_report(results: list[dict]) -> None:
    lines = ["# Dataset statistics (Phase 0)", "",
             "Generated by `python -m src.training.build_dataset`. Unit = one host x one 60 s window.",
             ""]
    for r in results:
        lines += [f"## {r['dataset']}", "",
                  "| capture | flows | hosts | windows | attack windows |", "|---|---|---|---|---|"]
        for c in r["captures"]:
            lines.append(f"| {c['capture']} | {c['flows']:,} | {c['hosts']} | {c['windows']:,} | "
                         f"{c['attack_windows']:,} |")
        lines += ["", "Windows per MITRE stage: " +
                  ", ".join(f"{k}={v:,}" for k, v in r["stage_windows"].items()), "",
                  "Top raw labels per capture:", ""]
        for c in r["captures"]:
            lines.append(f"- **{c['capture']}**: " + ", ".join(f"{k} ({v:,})" for k, v in c["labels"].items()))
        lines.append("")
    lines += ["## Not usable for per-host temporal modelling", "",
              "- **CIC-IDS2018**, 9 of 10 days: `TrafficForML` CSVs have no Src/Dst IP.",
              "- **CIC-IoT-2023**: flow-statistics rows without IPs or timestamps; there is no host "
              "timeline to learn transitions from. Not used for training (documented, not hidden).",
              "- **CIC-IDS2017 MachineLearningCVE**: duplicate of TrafficLabelling without IP/timestamp.", ""]
    (REPORTS / "dataset_stats.md").write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--datasets", nargs="+", default=list(DATASETS))
    args = ap.parse_args()
    PROCESSED.mkdir(parents=True, exist_ok=True)
    REPORTS.mkdir(parents=True, exist_ok=True)
    cfg = world_model_config()
    results = []
    for name in args.datasets:
        print(f"== {name}")
        results.append(build(name, cfg))
        (PROCESSED / f"{name}.stats.json").write_text(json.dumps(results[-1], indent=2, default=str))
    allres = []
    for name in DATASETS:
        p = PROCESSED / f"{name}.stats.json"
        if p.exists():
            allres.append(json.loads(p.read_text()))
    write_report(allres)


if __name__ == "__main__":
    main()
